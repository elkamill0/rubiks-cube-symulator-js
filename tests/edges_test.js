test("test_edges_inverse()", () => {
    const moves = ["R","L","U","D","F","B"];

    for (let i = 0; i < 30; i++) {
        const c = new Cube();
        randomMoves(c, 20);

        const start = structuredClone(c.edges);

        for (const m of moves) {
            const copy = c.clone();

            copy[m]();
            copy[m + "p"]();

            assertEqual(copy.edges, start, `${m} edges inverse failed`);
        }
    }
});

test("test_edges_4_identity()", () => {
    const moves = ["R","L","U","D","F","B"];

    for (const m of moves) {
        const c = new Cube();
        const start = structuredClone(c.edges);

        for (let i = 0; i < 4; i++) c[m]();

        assertEqual(c.edges, start, `${m}^4 edges failed`);
    }
});

test("test_edges_no_duplication()", () => {
    for (let i = 0; i < 30; i++) {
        const c = new Cube();
        randomMoves(c, 30);

        const indices = c.edges.map(e => e[0]);
        const unique = new Set(indices);

        assert(unique.size === 12, "Edge duplication");
    }
});


